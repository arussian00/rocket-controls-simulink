function spec = mc_dispersions()
%MC_DISPERSIONS  3-sigma dispersion table for the pitch-TVC Monte Carlo.
%
%   spec = mc_dispersions()
%
%   Each row is one independent draw. mc_sample draws it, mc_realize turns
%   the pitch-plant rows into a truth model, and mc_print_dispersions prints
%   the 1-sigma and 3-sigma ranges. Disabled rows stay at their nominal
%   value and are still copied onto plant.knobs, so a later step can turn
%   on lr_blend, a slosh or bending frequency, or grid-fin effectiveness
%   by editing this table. mc_realize applies the rows it knows. Anything
%   else waits on plant.knobs until that model exists.
%
%   Companion 1-sigma values are rocket_monte_carlo.m in matlab-rocket-sim:
%   thrust 2%, Isp 1%, drag 10%, dry mass 2%, wind 8 m/s. The 3-sigma
%   half-range is 3*sigma. mc_sample clips z to +/-3 and then to each row's
%   minimum and maximum.
%
%   Modes:
%     scale   value = nominal * (1 + sigma * z)     nominal is 1
%     offset  value = nominal + sigma * z
%     noise   value = sigma, the 1-sigma intensity (not a random scale)

spec = repmat(empty_row(), 1, 0);
spec = add_row(spec, "thrust", "scale", 1, 0.02, "1", ...
    "matlab-rocket-sim", [0.50 1.50], ...
    "Engine thrust scale. Companion sig.thrust = 0.02. 3-sigma is +/-6%.");
spec = add_row(spec, "isp", "scale", 1, 0.01, "1", ...
    "matlab-rocket-sim", [0.50 1.50], ...
    "Scales propellant still aboard on the fixed trajectory. Companion sig.Isp = 0.01. 3-sigma is +/-3%.");
spec = add_row(spec, "dryMass", "scale", 1, 0.02, "1", ...
    "matlab-rocket-sim", [0.50 1.50], ...
    "Inert-mass scale. Companion sig.dry = 0.02. 3-sigma is +/-6%.");
spec = add_row(spec, "cna", "scale", 1, 0.10, "1", ...
    "matlab-rocket-sim", [0.20 3.00], ...
    "Normal-force slope scale. Same 10% 1-sigma the companion uses for Cd. 3-sigma is +/-30%.");
spec = add_row(spec, "wind", "offset", 0, 8, "m/s", ...
    "matlab-rocket-sim", [-40 40], ...
    "Crosswind bias added to the 15 m/s design gust. Companion sig.wind = 8 m/s. 3-sigma is +/-24 m/s.");
spec = add_row(spec, "cg", "offset", 0, 0.40, "m", ...
    "design assumption", [-5 5], ...
    "CG forward of mid-length. 3-sigma is +/-1.2 m. Arm grows, and the static margin gets more stable, when this is positive.");
spec = add_row(spec, "inertia", "scale", 1, 0.03, "1", ...
    "design assumption", [0.50 1.50], ...
    "Extra factor on I about the realized CG. 3-sigma is +/-9%.");
spec = add_row(spec, "actBandwidth", "scale", 1, 0.10, "1", ...
    "design assumption", [0.40 1.80], ...
    "Scale on the 6 Hz servo. 3-sigma is +/-30% (4.2 to 7.8 Hz).");
spec = add_row(spec, "rateLimit", "scale", 1, 0.10, "1", ...
    "design assumption", [0.40 1.80], ...
    "Scale on the 20 deg/s gimbal-rate stop. 3-sigma is +/-30% (14 to 26 deg/s).");
spec = add_row(spec, "sensorDelay", "scale", 1, 0.25, "1", ...
    "design assumption", [0 3], ...
    "Scale on the 20 ms sensor delay. 3-sigma is +/-15 ms (5 to 35 ms).");
spec = add_row(spec, "sensorNoise", "noise", 0, 0.05, "deg", ...
    "design assumption", [0 1], ...
    "1-sigma attitude-measurement noise. 3-sigma is 0.15 deg. The envelope shows it. Pass/fail uses the noise-free error.");
spec = add_row(spec, "staticMargin", "offset", 0, 0.10, "cal", ...
    "design assumption", [-2 2], ...
    "Centre-of-pressure shift. 3-sigma is +/-0.30 caliber. Positive is more stable.");

% Reserved for the other steps. sigma 0 and enabled false.
spec = add_row(spec, "lr_blend", "offset", 0, 0, "1", ...
    "step 3 reserved", [0 1], ...
    "Max-q load-relief blend. Set enabled true and a sigma to disperse it.", false);
spec = add_row(spec, "sloshFreq", "scale", 1, 0, "1", ...
    "step 4 reserved", [0.20 5], ...
    "Scale on a future slosh frequency.", false);
spec = add_row(spec, "sloshMassFrac", "offset", 0, 0, "1", ...
    "step 4 reserved", [0 0.5], ...
    "Slosh mass fraction.", false);
spec = add_row(spec, "bendingFreq", "scale", 1, 0, "1", ...
    "step 4 reserved", [0.20 5], ...
    "Scale on a future bending frequency.", false);
spec = add_row(spec, "gridFinEff", "scale", 1, 0, "1", ...
    "step 5 reserved", [0 2], ...
    "Grid-fin effectiveness scale.", false);
end


function row = empty_row()
row = struct('name', "", 'mode', "", 'nominal', 0, 'sigma', 0, ...
    'unit', "", 'source', "", 'note', "", 'enabled', true, ...
    'minimum', -inf, 'maximum', inf);
end


function spec = add_row(spec, name, mode, nominal, sigma, unit, source, bounds, note, enabled)
if nargin < 10
    enabled = true;
end
row = empty_row();
row.name = name;
row.mode = mode;
row.nominal = nominal;
row.sigma = sigma;
row.unit = unit;
row.source = source;
row.note = note;
row.enabled = enabled;
row.minimum = bounds(1);
row.maximum = bounds(2);
if isempty(spec)
    spec = row;
else
    spec(end + 1) = row; %#ok<AGROW>
end
end
